    /** Один диалог — список реплик. */
    public record Dialogue(List<String> lines) {
        public static Dialogue of(String... l) { return new Dialogue(List.of(l)); }
    }

    public static List<Dialogue> pool(String... entries) {
        // Каждый элемент — диалог; реплики внутри разделяются символом «|».
        List<Dialogue> out = new ArrayList<>();
        for (String e : entries) out.add(new Dialogue(List.of(e.split("\\|"))));
        return out;
    }

    public static <T> T pick(List<T> list, Random r) { return list.get(r.nextInt(list.size())); }

